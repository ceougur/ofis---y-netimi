import path from "node:path";
import { pathToFileURL } from "node:url";
const [ROOT, FILE] = process.argv.slice(2).map(v => path.resolve(v));
const imp = file => import(pathToFileURL(path.join(ROOT, file)).href);
const { createClock } = await imp("server/lib/clock.mjs");
const { createStore, openDatabase } = await imp("server/lib/db.mjs");
const { createPeriod } = await imp("server/lib/period.mjs");
const { createRouter } = await imp("server/lib/router.mjs");
const { registerLedgerRoutes } = await imp("server/routes/ledger.mjs");
const { buildRule249 } = await imp("server/lib/ledger-rule-249/index.mjs");
const { leanStore } = await imp("server/lib/lean-rows.mjs");
const { sameEntries, printOf } = await imp("server/lib/ledger-snapshots.mjs");
const db = openDatabase(FILE, { readOnly: true });
const store = createStore(db);
const now = createClock({ time: "2026-10-08T12:00:00+03:00", fixed: true });
const ledger = registerLedgerRoutes(createRouter(), { store, now, auth: null, audit: () => {}, events: null, period: createPeriod({ store, now }), integrity: () => null, money: null, config: {} });
const t = label => { const s = performance.now(); return () => console.log(label, Math.round(performance.now() - s), "ms"); };
let done = t("güncel türetme");
const fresh = ledger.build();
done();
done = t("2.4.9 türetme");
const old = buildRule249(leanStore(store));
done();
const range = entries => entries.filter(entry => entry.date <= "2025-12-31");
done = t("süzme ×2");
const a = range(fresh);
const b = range(old);
done();
done = t("sameEntries");
console.log("aynı mı", sameEntries(b, a), a.length);
done();
done = t("printOf");
printOf(a);
done();
db.close();
